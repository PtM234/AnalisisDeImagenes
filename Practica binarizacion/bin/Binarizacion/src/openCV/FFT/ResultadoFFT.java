    private File elegirImagen(){        //Elegir imagen para abrir
        JFileChooser e = new JFileChooser();
        e.setDialogTitle("Elegir imagen");
        e.setFileFilter(new FileNameExtensionFilter("Imágenes (JPG, PNG)", "jpg", "jpeg", "png"));
        e.setAcceptAllFileFilterUsed(false);
        
        if (e.showOpenDialog(this) == JFileChooser.APPROVE_OPTION){
            return e.getSelectedFile();
        } else{
            return null;
        }
    }
    
    private static Mat leerImagen(File archivoAConvertir) throws IOException{
        byte[] bytes = Files.readAllBytes(archivoAConvertir.toPath());
        return Imgcodecs.imdecode(new MatOfByte(bytes), Imgcodecs.IMREAD_GRAYSCALE);
    }
    
    public static Mat fft(Mat img){
        Mat f = new Mat();
        img.convertTo(f, CvType.CV_32F);
        
        int filas = Core.getOptimalDFTSize(img.rows());
        int columnas = Core.getOptimalDFTSize(img.cols());
        while (filas % 2 != 0) filas = Core.getOptimalDFTSize(filas + 1);
        while (columnas  % 2 != 0) columnas  = Core.getOptimalDFTSize(columnas + 1);
        
        Mat relleno = new Mat();
        Core.copyMakeBorder(f, relleno, 0, filas - img.rows(), 0, columnas - img.cols(),Core.BORDER_CONSTANT, Scalar.all(0));
        
        List<Mat> planos = new ArrayList<>();
        planos.add(relleno);
        planos.add(Mat.zeros(relleno.size(), CvType.CV_32F));
        Mat complejo = new Mat();
        Core.merge(planos, complejo);

        Core.dft(complejo, complejo, Core.DFT_COMPLEX_OUTPUT);
        shift(complejo);
        return complejo;
        
    }
    
    public static Mat espectro(Mat complejo) {
        List<Mat> planos = new ArrayList<>();
        Core.split(complejo, planos);
        Mat mag = new Mat();
        Core.magnitude(planos.get(0), planos.get(1), mag);
        Core.add(mag, Scalar.all(1), mag);
        Core.log(mag, mag);
        Core.normalize(mag, mag, 0, 255, Core.NORM_MINMAX);
        mag.convertTo(mag, CvType.CV_8U);
        return mag;
    }
    
    public static void shift(Mat m) {
        int cx = m.cols() / 2, cy = m.rows() / 2;
        Mat q0 = new Mat(m, new Rect(0, 0, cx, cy));
        Mat q1 = new Mat(m, new Rect(cx, 0, cx, cy));
        Mat q2 = new Mat(m, new Rect(0, cy, cx, cy));
        Mat q3 = new Mat(m, new Rect(cx, cy, cx, cy));
        Mat tmp = new Mat();
        q0.copyTo(tmp); q3.copyTo(q0); tmp.copyTo(q3);
        q1.copyTo(tmp); q2.copyTo(q1); tmp.copyTo(q2);
    }
    
    public static Mat ifft(Mat complejo, Size original) {
        Mat c = complejo.clone();
        shift(c);
        Mat r = new Mat();
        Core.idft(c, r, Core.DFT_SCALE | Core.DFT_REAL_OUTPUT);
        r = r.submat(new Rect(0, 0, (int) original.width, (int) original.height));
        Mat salida = new Mat();
        r.convertTo(salida, CvType.CV_8U);
        return salida;
    }
    
    private static BufferedImage matABufferedImage(Mat mat) {
        if (!mat.isContinuous()) mat = mat.clone();
        int tipo = (mat.channels() == 1) ? BufferedImage.TYPE_BYTE_GRAY
                                         : BufferedImage.TYPE_3BYTE_BGR;
        BufferedImage img = new BufferedImage(mat.cols(), mat.rows(), tipo);
        byte[] destino = ((DataBufferByte) img.getRaster().getDataBuffer()).getData();
        mat.get(0, 0, destino);
        return img;
    }
    
    public void mostrarImagen(JLabel label, Mat mat, String titulo){
        BufferedImage bi = matABufferedImage(mat);
        double escala = Math.min(1.0, (double) 230 / Math.max(bi.getWidth(), bi.getHeight()));
        int w = (int) (bi.getWidth() * escala);
        int h = (int) (bi.getHeight() * escala);
        label.setIcon(new ImageIcon(bi.getScaledInstance(w, h, Image.SCALE_SMOOTH)));
        label.setText(null);
        label.setHorizontalAlignment(JLabel.CENTER);
        label.setBorder(BorderFactory.createTitledBorder(titulo));
    }
    
    public void procesar() {
        File archivo = elegirImagen();
        if (archivo == null) {
            System.exit(0);            
            return;
        }

        Mat img;
        try {
            img = leerImagen(archivo);
        } catch (IOException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al leer:\n" + ex.getMessage());
            return;
        }
        if (img.empty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo decodificar la imagen");
            return;
        }

        Mat F   = fft(img);
        Mat esp = espectro(F);
        Mat rec = ifft(F, img.size());

        setTitle("FFT - " + archivo.getName());
        mostrarImagen(lblOriginal,  img, "Original");
        mostrarImagen(lblEspectro,  esp, "Espectro |F(u,v)|");
        mostrarImagen(lblResultado, rec, "Resultado");
    }

